export type MessageKey = keyof typeof messages;
type TranslationValues = Record<string, string | number>;

const catalog: Record<Locale, { [Key in keyof typeof messages]: string }> = { es: messages, gl: galicianMessages, eu: basqueMessages, ca: catalanMessages };
const LocaleContext = createContext<Locale>('es');
const LocaleSetterContext = createContext<(locale: Locale) => void>(() => undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
    const [locale, setLocale] = useState<Locale>(() => {
        try {
            const savedLocale = window.localStorage.getItem('gases-locale');
            if (savedLocale && AVAILABLE_LOCALES.includes(savedLocale as Locale)) return savedLocale as Locale;
        } catch {
            // Use the browser preference if local storage is unavailable.
        }
        if (typeof navigator === 'undefined') return 'es';
        const languages = navigator.languages.map((language) => language.toLowerCase());
        if (languages.some((language) => language.startsWith('ca'))) return 'ca';
        if (languages.some((language) => language.startsWith('eu'))) return 'eu';
        return languages.some((language) => language.startsWith('gl')) ? 'gl' : 'es';
    });

    useEffect(() => {
        document.documentElement.lang = locale === 'ca' ? 'ca-ES' : locale === 'gl' ? 'gl-ES' : locale === 'eu' ? 'eu-ES' : 'es-ES';
        document.querySelector('meta[name="description"]')?.setAttribute('content', translate(locale, 'app.description'));
        document.title = translate(locale, 'app.title');
        try {
            window.localStorage.setItem('gases-locale', locale);
        } catch {
            // Locale changes remain available for the current session.
        }
    }, [locale]);

    return <LocaleSetterContext.Provider value={setLocale}><LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider></LocaleSetterContext.Provider>;
}

function translate(locale: Locale, key: MessageKey, values?: TranslationValues): string {
    const template: string = catalog[locale][key];
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
}

export function useTranslation() {
    const locale = useContext(LocaleContext);
    const setLocale = useContext(LocaleSetterContext);
    return {
        locale,
        setLocale,
        t: (key: MessageKey, values?: TranslationValues) => translate(locale, key, values),
        formatLocale: locale === 'ca' ? 'ca-ES' : locale === 'gl' ? 'gl-ES' : locale === 'eu' ? 'eu-ES' : 'es-ES',
    };
}
